"""Synthetic temporal graphs with tunable causal topology (Scholtes et al., Nat. Commun. 2014), used for RQ3.

Two k-regular random communities are linked by a few edges. Temporal graphs are generated by
second-order random walks of length two whose transition weights are controlled by `sigma`:
for sigma > 0 time-respecting paths across communities are over-, for sigma < 0 underrepresented
compared to sigma = 0, while the time-aggregated graph is identical for all sigma.
"""

import random

import pathpyG as pp
import torch


def natcom_model_fo(k: int, n: int, inter_com: int = 1):
    """First-order graph: two k-regular communities of n nodes each, connected by 2*inter_com edges.

    Returns the undirected graph and the list of inter-community edges.
    """
    g1 = pp.algorithms.generative_models.k_regular_random(k, n)
    g2 = pp.algorithms.generative_models.k_regular_random(k, n)

    g1.mapping = pp.IndexMap([f'{v}_g1' for v in g1.nodes])
    g2.mapping = pp.IndexMap([f'{v}_g2' for v in g2.nodes])

    g3 = (g1 + g2).to_undirected()
    edge_list = g3.edges

    el_1 = [e for e in edge_list if e[0].endswith('g1')]
    el_2 = [e for e in edge_list if e[0].endswith('g2')]
    inter_com_edges = []

    # rewire one edge of each community into two inter-community edges
    for _ in range(inter_com):
        e1 = random.choice(el_1)
        e2 = random.choice(el_2)

        el_1.remove(e1)
        el_1.remove((e1[1], e1[0]))
        el_2.remove(e2)
        el_2.remove((e2[1], e2[0]))

        inter_com_edges.append((e1[0], e2[0]))
        inter_com_edges.append((e1[1], e2[1]))

    new_edges = el_1 + el_2 + inter_com_edges
    g = pp.Graph.from_edge_list(new_edges, mapping=g3.mapping).to_undirected()
    return g, inter_com_edges


def natcom_model_ho(g: pp.Graph, inter_com_edges, sigma: float = 1, w2: float = 1) -> pp.Graph:
    """Second-order graph of `g` whose edge weights favour (sigma > 0) or suppress (sigma < 0) paths across communities."""
    _, _, _, g_ho = pp.MultiOrderModel.iterate_lift_order(
        g.data.edge_index, node_sequence=torch.arange(g.data.num_nodes).unsqueeze(1), mapping=g.mapping
    )

    edge_weights = {}
    for e in inter_com_edges:
        edge_weights[(e, (e[1], e[0]))] = w2 * (1 - sigma)
        edge_weights[((e[1], e[0]), e)] = w2 * (1 - sigma)

        for n in g.successors(e[0]):
            if not n == e[1]:
                edge_weights[((n, e[0]), (e[0], n))] = w2 * (1 - sigma)
                edge_weights[((e[0], n), (n, e[0]))] = w2 * (1 - sigma)

                edge_weights[((n, e[0]), e)] = w2 * (1 + sigma)
                edge_weights[((e[1], e[0]), (e[0], n))] = w2 * (1 + sigma)

        for n in g.successors(e[1]):
            if not n == e[0]:
                edge_weights[((e[1], n), (n, e[1]))] = w2 * (1 - sigma)
                edge_weights[((n, e[1]), (e[1], n))] = w2 * (1 - sigma)

                edge_weights[(e, (e[1], n))] = w2 * (1 + sigma)
                edge_weights[((n, e[1]), (e[1], e[0]))] = w2 * (1 + sigma)

    weights = [edge_weights.get(e, w2) for e in g_ho.edges]
    g_ho.data["edge_weights"] = torch.tensor(weights).view(-1, 1)
    return g_ho


def temporal_graph_from_natcom(g: pp.Graph, inter_com_edges, sigma: float = 1, w2: float = 1,
                               runs: int = 200, steps: int = 2) -> pp.TemporalGraph:
    """Temporal graph from `runs` second-order random walks with `steps` steps on the second-order graph.

    Consecutive edges of a walk get timestamps t and t + 1; walks are separated by a gap of one time unit.
    """
    g_ho = natcom_model_ho(g, inter_com_edges, sigma=sigma, w2=w2)

    rw = pp.processes.HigherOrderRandomWalk(g_ho, g, weight="edge_weights")
    data = rw.run_experiment(steps=steps, runs=runs)
    p = rw.get_paths(data)

    edge_list = []
    t = 0
    for i in range(runs):
        path = p.get_walk(i)
        for j in range(len(path) - 1):
            edge_list.append((path[j], path[j + 1], t))
            t += 1
        t += 1

    temp_net = pp.TemporalGraph.from_edge_list(edge_list)
    temp_net.data["y"] = 0 if sigma > 0 else 1
    return temp_net
