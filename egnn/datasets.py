"""Dataset names, waiting times and the directory layout shared by all scripts.

Empirical data (RQ1/RQ2), generated by ``scripts/generate_empirical_data.py``::

    data/processed/{representation}/{dataset}/slice{s}/class{c}/{dataset}_slice{s}_c{c}_{i}.pickle
    data/processed/temporal/{dataset}/slice{s}/meta.json

with representation ``temporal`` (pathpyG temporal graphs), ``augmented`` (augmented event graphs) or
``concat`` (time-concatenated static graphs). Classes 1 and 3 preserve the time-respecting paths of the
slice, classes 2 and 4 do not.

Synthetic data (RQ3), generated by ``scripts/generate_synthetic_data.py``::

    data/processed/synthetic/{representation}/sigma{sigma}/net{i}.pkl

with representation ``temporal``, ``compressed`` (compressed augmented event graphs) or ``concat``.
"""

import os
from pathlib import Path

DATA_DIR = Path('data')
RAW_DIR = DATA_DIR / 'raw'
PROCESSED_DIR = DATA_DIR / 'processed'
RESULTS_DIR = Path('results')

# maximum waiting time delta (in seconds) per empirical dataset, see Table 3
EMPIRICAL_DATASETS = {
    'ants_1_1': 30,
    'ants_1_2': 30,
    'sociopatterns_workplace': 3600,
    'sociopatterns_hospital': 3600,
    'eu_email_dept2': 3600,
}

POSITIVE_CLASSES = (1, 3)
NEGATIVE_CLASSES = (2, 4)

SIGMAS = [round(0.1 * i, 1) for i in range(-9, 10)]


def sigma_str(sigma: float) -> str:
    return f'{sigma:g}'


def num_slices(dataset: str, root: Path = PROCESSED_DIR) -> int:
    return len([d for d in os.listdir(root / 'temporal' / dataset) if d.startswith('slice')])


def task_files(dataset: str, slice: int, representation: str = 'augmented', root: Path = PROCESSED_DIR):
    """`(path, label)` pairs of one slice: label 1 for classes 1/3, label 0 for classes 2/4."""
    folder = root / representation / dataset / f'slice{slice}'
    files = []
    for label, classes in ((1, POSITIVE_CLASSES), (0, NEGATIVE_CLASSES)):
        for c in classes:
            class_dir = folder / f'class{c}'
            files += [(class_dir / f, label) for f in sorted(os.listdir(class_dir)) if f.endswith('.pickle')]
    return files


def synthetic_files(sigma: float, label: int, representation: str = 'compressed', root: Path = PROCESSED_DIR,
                    max_graphs: int = 250):
    """`(path, label)` pairs of the first `max_graphs` synthetic graphs generated with `sigma`."""
    folder = root / 'synthetic' / representation / f'sigma{sigma_str(sigma)}'
    files = sorted(f for f in os.listdir(folder) if f.endswith('.pkl'))
    return [(folder / f, label) for f in files[:max_graphs]]
